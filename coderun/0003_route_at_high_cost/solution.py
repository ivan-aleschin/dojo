def main():
    # Читаем размеры таблицы N × M
    n, m = map(int, input().split())

    # Читаем саму таблицу в двумерный список
    grid = []
    for _ in range(n):
        grid.append(list(map(int, input().split())))

    # Инициализируем таблицу динамического программирования
    # dp[i][j] будет содержать максимальную сумму при достижении клетки (i, j)
    dp = [[0] * m for _ in range(n)]

    # Базовый случай: начальная клетка (0, 0)
    dp[0][0] = grid[0][0]

    # Заполняем первую строку
    # В первой строке можно двигаться только вправо
    for j in range(1, m):
        dp[0][j] = dp[0][j - 1] + grid[0][j]

    # Заполняем первый столбец
    # В первом столбце можно двигаться только вниз
    for i in range(1, n):
        dp[i][0] = dp[i - 1][0] + grid[i][0]

    # Заполняем остальную таблицу DP
    # Для каждой клетки (i, j) выбираем максимум из двух возможных путей:
    # - пришли снизу (из (i-1, j))
    # - пришли слева (из (i, j-1))
    for i in range(1, n):
        for j in range(1, m):
            dp[i][j] = max(dp[i - 1][j], dp[i][j - 1]) + grid[i][j]

    # Восстанавливаем путь, идя с конца таблицы (правый нижний угол) к началу
    path = []
    curr_i, curr_j = n - 1, m - 1

    # Двигаемся назад до тех пор, пока не достигнем начала (0, 0)
    while curr_i > 0 or curr_j > 0:
        if curr_i == 0:
            # Если мы в первой строке, можно двигаться только вправо
            # Значит в прямом направлении мы двигались вправо (R)
            path.append("R")
            curr_j -= 1
        elif curr_j == 0:
            # Если мы в первом столбце, можно двигаться только вниз
            # Значит в прямом направлении мы двигались вниз (D)
            path.append("D")
            curr_i -= 1
        else:
            # Если мы внутри таблицы, проверяем откуда мы пришли
            # Сравниваем значения DP сверху и слева
            if dp[curr_i - 1][curr_j] > dp[curr_i][curr_j - 1]:
                # Пришли сверху, значит двигались вниз (D)
                path.append("D")
                curr_i -= 1
            else:
                # Пришли слева, значит двигались вправо (R)
                path.append("R")
                curr_j -= 1

    # Выводим результаты
    # Максимальная сумма находится в dp[n-1][m-1]
    print(dp[n - 1][m - 1])
    # Путь собирали в обратном порядке, поэтому разворачиваем его
    print(*(path[::-1]))


if __name__ == "__main__":
    main()
