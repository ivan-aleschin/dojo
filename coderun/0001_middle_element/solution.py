def main():
    # Читаем три числа со входа и преобразуем их в список целых чисел
    # input().split() разбивает строку по пробелам, map(int, ...) преобразует каждое значение в целое число
    numbers = list(map(int, input().split()))

    # Сортируем список чисел по возрастанию
    # После сортировки: numbers[0] - минимальное, numbers[1] - среднее, numbers[2] - максимальное
    numbers.sort()

    # Выводим средний элемент с индексом 1
    # Это и есть число, которое находится между двумя другими
    print(numbers[1])


if __name__ == "__main__":
    main()
